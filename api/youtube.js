// Fetch a YouTube video's captions with the user's Apify token (x-apify-key header).
// Uses Apify's "YouTube Scraper" (streamers/youtube-scraper) in subtitles-only mode.
// The token is used for this request only and is never stored or logged.
import { header, readBody } from "./_db.js";

const ACTOR = "streamers~youtube-scraper";

export function parseSrt(srt) {
  const toSec = t => { const m = String(t).match(/(\d+):(\d{2}):(\d{2})[,.](\d{1,3})/); return m ? +m[1] * 3600 + +m[2] * 60 + +m[3] + +m[4] / 1000 : 0; };
  const out = [];
  for (const block of String(srt || "").replace(/\r/g, "").split(/\n{2,}/)) {
    const lines = block.split("\n").map(s => s.trim()).filter(Boolean);
    const ti = lines.findIndex(l => l.includes("-->"));
    if (ti < 0) continue;
    const [a, b] = lines[ti].split("-->");
    const text = lines.slice(ti + 1).join(" ").replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
    if (!text) continue;
    const prev = out[out.length - 1];
    if (prev && (prev.text === text || prev.text.endsWith(text))) { prev.end = toSec(b); continue; } // rolling auto-captions repeat lines
    if (prev && text.startsWith(prev.text)) { prev.text = text; prev.end = toSec(b); continue; }
    out.push({ start: toSec(a), end: toSec(b), text });
  }
  return out;
}

const durSec = d => {
  if (typeof d === "number") return d;
  const p = String(d || "").split(":").map(Number);
  return p.length && p.every(Number.isFinite) ? p.reduce((s, x) => s * 60 + x, 0) : null;
};

export default async function handler(req, res) {
  res.setHeader("Cache-Control", "no-store");
  if (req.method !== "POST") { res.setHeader("Allow", "POST"); return res.status(405).json({ ok: false, error: "Use POST." }); }
  const apifyKey = header(req, "x-apify-key");
  const url = String(readBody(req).url || "").trim();
  if (!/^https:\/\/www\.youtube\.com\/watch\?v=[A-Za-z0-9_-]{6,}$/.test(url)) return res.status(400).json({ ok: false, error: "That doesn't look like a YouTube video link." });
  if (!apifyKey) return res.status(400).json({ ok: false, code: "keys", error: "Add your Apify API token in API keys." });

  let r;
  try {
    r = await fetch(`https://api.apify.com/v2/acts/${ACTOR}/run-sync-get-dataset-items?timeout=270`, {
      method: "POST",
      headers: { Authorization: `Bearer ${apifyKey}`, "Content-Type": "application/json" },
      body: JSON.stringify({
        startUrls: [{ url }],
        maxResults: 1, maxResultsShorts: 1, maxResultStreams: 1,
        transcriptionAndSubtitle: "ALWAYS_SUBTITLES",
        subtitlesLanguage: "any",
        subtitlesFormat: "srt",
        preferAutoGeneratedSubtitles: false,
        saveSubsToKVS: false,
      }),
    });
  } catch {
    return res.status(502).json({ ok: false, error: "Couldn't reach Apify. Try again in a minute." });
  }
  if (r.status === 401 || r.status === 403) return res.status(400).json({ ok: false, code: "apifykey", error: "Apify rejected this token, or its monthly credit is used up." });
  if (r.status === 402) return res.status(400).json({ ok: false, code: "apifykey", error: "This Apify account is out of credit for the month." });
  const text = await r.text();
  if (!r.ok) return res.status(502).json({ ok: false, error: `Apify error ${r.status}. ${text.slice(0, 160)}` });
  let items;
  try { items = JSON.parse(text); } catch { return res.status(502).json({ ok: false, error: "Apify returned something unexpected." }); }
  const item = (Array.isArray(items) ? items : []).find(x => x && !x.error) || null;
  if (!item) return res.status(422).json({ ok: false, error: "Apify couldn't open this video. It may be private, age-restricted or removed." });

  const subs = Array.isArray(item.subtitles) ? item.subtitles.filter(s => s && s.srt) : [];
  const pick = subs.find(s => !/auto/i.test(s.type || "")) || subs[0];
  const segments = pick ? parseSrt(pick.srt) : [];
  if (!segments.length) {
    return res.status(422).json({ ok: false, error: "This video has no captions on YouTube, so there is no transcript to read. Videos without captions aren't supported yet." });
  }
  const chUrl = String(item.channelUrl || "");
  const handle = (chUrl.match(/youtube\.com\/(@[^/?#]+|channel\/[^/?#]+|c\/[^/?#]+|user\/[^/?#]+)/) || [])[1] || item.channelName || "unknown";
  return res.status(200).json({
    ok: true,
    url,
    title: item.title || "",
    channelName: item.channelName || "",
    channelUrl: chUrl,
    handle: decodeURIComponent(handle),
    duration: durSec(item.duration),
    thumbnail: item.thumbnailUrl || "",
    description: String(item.text || "").slice(0, 5000),
    language: pick.language || "",
    captionType: pick.type || "",
    segments,
  });
}
